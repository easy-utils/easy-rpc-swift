#!/usr/bin/env python3
# protoc-gen-easyrpc-swift: emit <file>_easyrpc.swift with a method table.
import sys
from google.protobuf.compiler import plugin_pb2 as plugin

def resolve(f):
    out=[]
    pkg=f.package.replace('.','_').replace('-','_') or ''
    for svc in f.service:
        for m in svc.method:
            out.append((svc.name, m.name or '', f'/{f.package}.{svc.name}/{m.name}', m.server_streaming))
    return out

def main():
    data=sys.stdin.buffer.read()
    req=plugin.CodeGeneratorRequest.FromString(data)
    files=[]
    for f in req.proto_file:
        if f.name not in req.file_to_generate: continue
        ms=resolve(f)
        if not ms: continue
        base=f.name[:-6]
        lines=['// Code generated by protoc-gen-easyrpc-swift. DO NOT EDIT.',
               'import easyRpc', '', 'public struct EasyRpcMethod { public let service: String; public let name: String; public let path: String; public let serverStream: Bool; public init(_ s:String,_ n:String,_ p:String,_ ss:Bool){service=s;name=n;path=p;serverStream=ss} }',
               '', 'public let easyRpcMethodSpecs: [EasyRpcMethod] = [']
        for (svc,name,path,ss) in ms:
            lines.append(f'  EasyRpcMethod("{svc}","{name}","{path}",{str(ss).lower()}),')
        lines.append(']')
        lines.append('')
        content='\n'.join(lines)
        files.append(plugin.CodeGeneratorResponse.File(name=base+'_easyrpc.swift', content=content))
    resp=plugin.CodeGeneratorResponse(file=files)
    sys.stdout.buffer.write(resp.SerializeToString())

if __name__=='__main__': main()
